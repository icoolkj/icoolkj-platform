/**
 * Sync platform i18n Git baseline (error / entity.name / validation / notify).
 * - Merges scripts/i18n-seed/messages_*.properties into dual-end i18n/platform JSON
 * - Does NOT seed those keys into sys_i18n_message (V3 / SQL)
 *
 * Usage: node scripts/generate-i18n-seed.mjs
 *
 * Optional remaining non-platform backend keys in properties would still be written to
 * backend/database/migration/V7_1__i18n_message_seed.sql (idempotent INSERT).
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.join(__dirname, '..')
const outputPath = path.join(root, 'scripts', 'i18n-seed', 'generated-backend-overrides.sql')

const PLATFORM_RE = /^(error|entity\.name|validation|notify|oa\.instance)\./

const FE_PLATFORM = path.join(root, 'frontend', 'src', 'i18n', 'platform')
const BE_PLATFORM = path.join(
  root,
  'backend',
  'icoolkj-admin-system',
  'src',
  'main',
  'resources',
  'i18n',
  'platform',
)

function escapeSql(value) {
  return value.replace(/\\/g, '\\\\').replace(/'/g, "''")
}

function parseProperties(content) {
  const map = {}
  for (const line of content.split('\n')) {
    const trimmed = line.trim()
    if (!trimmed || trimmed.startsWith('#')) continue
    const idx = trimmed.indexOf('=')
    if (idx <= 0) continue
    map[trimmed.slice(0, idx).trim()] = trimmed.slice(idx + 1).trim()
  }
  return map
}

function moduleOf(key) {
  return key.split('.')[0] || 'common'
}

function sortObject(obj) {
  return Object.fromEntries(Object.keys(obj).sort().map((k) => [k, obj[k]]))
}

function readJsonMap(filePath) {
  if (!fs.existsSync(filePath)) return {}
  return JSON.parse(fs.readFileSync(filePath, 'utf8'))
}

function writePlatformLocale(locale, map) {
  const json = JSON.stringify(sortObject(map), null, 2) + '\n'
  fs.mkdirSync(FE_PLATFORM, { recursive: true })
  fs.mkdirSync(BE_PLATFORM, { recursive: true })
  fs.writeFileSync(path.join(FE_PLATFORM, `${locale}.json`), json, 'utf8')
  fs.writeFileSync(path.join(BE_PLATFORM, `${locale}.json`), json, 'utf8')
}

/** Additive only: properties fill missing keys; existing JSON (fuller V3 extract) wins. */
function syncPlatformFromProperties(zhProps, enProps) {
  const zh = readJsonMap(path.join(FE_PLATFORM, 'zh-CN.json'))
  const en = readJsonMap(path.join(FE_PLATFORM, 'en-US.json'))
  let added = 0
  for (const [k, v] of Object.entries(zhProps)) {
    if (PLATFORM_RE.test(k) && !(k in zh)) {
      zh[k] = v
      added++
    }
  }
  for (const [k, v] of Object.entries(enProps)) {
    if (PLATFORM_RE.test(k) && !(k in en)) {
      en[k] = v
      added++
    }
  }
  writePlatformLocale('zh-CN', zh)
  writePlatformLocale('en-US', en)
  return { zhKeys: Object.keys(zh).length, enKeys: Object.keys(en).length, added }
}

function rowsFromMap(map, locale, scope) {
  return Object.entries(map).map(([messageKey, messageValue]) => ({
    messageKey,
    locale,
    messageValue,
    module: moduleOf(messageKey),
    scope,
  }))
}

function buildSql(rows) {
  if (!rows.length) {
    return [
      '-- Generated by scripts/generate-i18n-seed.mjs',
      '-- No non-platform backend keys left in messages_*.properties.',
      '-- Platform fixed copy lives in i18n/platform/ (Git baseline; DB optional overrides).',
      '',
    ].join('\n')
  }
  const lines = [
    '-- Generated by scripts/generate-i18n-seed.mjs (non-platform backend keys only)',
    'set names utf8mb4;',
    '',
  ]
  for (const row of rows) {
    lines.push(
      `insert into sys_i18n_message (message_key, locale, message_value, module, scope) select '${escapeSql(row.messageKey)}', '${row.locale}', '${escapeSql(row.messageValue)}', '${escapeSql(row.module)}', '${row.scope}' where not exists (select 1 from sys_i18n_message m where m.message_key='${escapeSql(row.messageKey)}' and m.locale='${row.locale}');`,
    )
  }
  return lines.join('\n') + '\n'
}

function main() {
  const propsDir = path.join(root, 'scripts', 'i18n-seed')
  const zhProps = parseProperties(fs.readFileSync(path.join(propsDir, 'messages_zh_CN.properties'), 'utf8'))
  const enProps = parseProperties(fs.readFileSync(path.join(propsDir, 'messages_en_US.properties'), 'utf8'))

  const sync = syncPlatformFromProperties(zhProps, enProps)
  console.log(
    `Synced i18n/platform dual-end: zh=${sync.zhKeys} en=${sync.enKeys} (added from properties=${sync.added})`,
  )

  const zhOther = Object.fromEntries(Object.entries(zhProps).filter(([k]) => !PLATFORM_RE.test(k)))
  const enOther = Object.fromEntries(Object.entries(enProps).filter(([k]) => !PLATFORM_RE.test(k)))
  const rows = [
    ...rowsFromMap(zhOther, 'zh-CN', 'backend'),
    ...rowsFromMap(enOther, 'en-US', 'backend'),
  ]

  fs.writeFileSync(outputPath, buildSql(rows), 'utf8')
  console.log(`Wrote ${rows.length} non-platform backend SQL rows to ${outputPath}`)
}

main()
